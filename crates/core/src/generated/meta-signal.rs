#![allow(
    dead_code,
    non_camel_case_types,
    non_snake_case,
    clippy::type_complexity
)]
#[rustfmt::skip]
#[derive(rkyv::Archive, rkyv::Serialize, rkyv::Deserialize, Clone, Debug, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "datom", derive(datom_codec::Datomizable, datom_codec::Composing))]
pub enum Setting {
    Homeserver(messenger::Homeserver),
    RoomId(messenger::RoomId),
    LivingUserId(messenger::LivingUserId),
    CredentialPath(messenger::CredentialPath),
    CryptoStorePath(messenger::CryptoStorePath),
    Communicator(flow::Address),
    FlowClientPath(messenger::FlowClientPath),
}
#[rustfmt::skip]
#[derive(rkyv::Archive, rkyv::Serialize, rkyv::Deserialize, Clone, Debug, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "datom", derive(datom_codec::Datomizable, datom_codec::Composing))]
pub enum Input {
    Configure(Setting),
    Observe,
}
#[rustfmt::skip]
#[derive(rkyv::Archive, rkyv::Serialize, rkyv::Deserialize, Clone, Debug, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "datom", derive(datom_codec::Datomizable, datom_codec::Composing))]
pub enum Output {
    Configured,
    Observed(messenger::Configuration),
    Refused(messenger::Reason),
    Changed(messenger::Configuration),
}
#[rustfmt::skip]
#[allow(clippy::result_large_err, clippy::ptr_arg, clippy::borrowed_box)]
pub trait Answering {
    fn configure(&self, setting: &Setting) -> std::result::Result<(), Output>;
    fn observe(&self) -> std::result::Result<messenger::Configuration, Output>;
}
#[rustfmt::skip]
pub trait Answerable {
    type Answer;
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Self::Answer;
}
#[rustfmt::skip]
impl Answerable for Input {
    type Answer = Output;
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Output {
        match self {
            Input::Configure(carried) => {
                nexus
                    .configure(carried)
                    .map_or_else(|refusal| refusal, |()| Output::Configured)
            }
            Input::Observe => {
                nexus.observe().map_or_else(|refusal| refusal, Output::Observed)
            }
        }
    }
}
